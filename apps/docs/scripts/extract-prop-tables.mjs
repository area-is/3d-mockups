/**
 * Generates lib/prop-tables.generated.ts: every prop each mockup accepts,
 * lifted from the prop tables already written in the API docs.
 *
 * The prop explorer drives a subset of these interactively; the rest it lists
 * as code-only, so the inspector shows the whole surface rather than only the
 * parts it has a control for. Reading the docs rather than restating them
 * keeps one source of truth - the table a maintainer already updates.
 *
 * Run automatically before `next dev` / `next build`; the output is committed
 * so typecheck works without running it.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEVICES, OBJECTS } from '../lib/mockup-catalog.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** Which shared reference documents each device family. */
const FAMILY_OF = {
  GalaxyMockup: 'galaxy',
  IPhoneMockup: 'iphone',
  FoldMockup: 'fold',
  FlipMockup: 'flip',
  LaptopMockup: 'laptop',
  IPadMockup: 'ipad',
  GalaxyTabMockup: 'galaxy-tab',
  AppleWatchMockup: 'apple-watch',
  GalaxyWatchMockup: 'galaxy-watch',
  StudioDisplayMockup: 'studio-display',
}

/** Strip markdown emphasis, links and code ticks down to plain text. */
const plain = (cell) =>
  cell
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[`*]/g, '')
    .trim()

/**
 * Split one markdown table row into its cells.
 *
 * A union type is written `'s26' \| 's26ultra'` - the pipe is escaped so the
 * table survives, and unescaping it here is what keeps `'s26' | 's26ultra'`
 * in one cell instead of shearing the row into `'s26'`, `'s26ultra'`, and a
 * description that lands three columns to the left.
 */
function rowCells(line) {
  const out = []
  let cell = ''
  for (let i = 0; i < line.length; i++) {
    if (line[i] === '\\' && line[i + 1] === '|') {
      cell += '|'
      i++
    } else if (line[i] === '|') {
      out.push(cell)
      cell = ''
    } else {
      cell += line[i]
    }
  }
  out.push(cell)
  return out.slice(1, -1)
}

/**
 * The first `| Prop | Type | Default | Description |` table in a document.
 * Rows whose prop cell lists several names (`position` / `rotation` / `scale`)
 * are split, so each lands as its own row.
 */
function propTable(markdown) {
  const lines = markdown.split('\n')
  const start = lines.findIndex((l) => /^\|\s*Prop\s*\|/i.test(l))
  if (start === -1) return []
  const out = []
  for (let i = start + 2; i < lines.length; i++) {
    const line = lines[i]
    if (!line.startsWith('|')) break
    const cells = rowCells(line)
    if (cells.length < 3) break
    const [name, type, def, description = ''] = cells
    for (const one of plain(name).split(/[/,]/)) {
      const propName = one.trim()
      if (!propName) continue
      out.push({
        name: propName,
        type: plain(type) || '-',
        default: plain(def) || '-',
        description: plain(description),
      })
    }
  }
  return out
}

const read = (path) => (existsSync(path) ? readFileSync(path, 'utf8') : '')

/*
 * Props every mockup takes, gathered from where each is documented: the
 * shared-props table, the screen-surface table, and MockupCanvas - whose
 * stage props a mockup forwards wholesale. `children` appears in more than
 * one, so it is settled here.
 *
 * Three rows of the MockupCanvas table are NOT part of that forwarded set:
 * `freeRotation`, `shadowY` and `dpr` tune the rendering machinery rather than
 * the picture, and Components overview says so in as many words - a mockup
 * does not advertise them, and `MockupProps` leaves them off the type. Listing
 * them as props of a mockup would send a reader to code that does not compile;
 * they belong to MockupCanvas, and the MockupCanvas page documents them.
 */
const CANVAS_ONLY_MACHINERY = new Set(['freeRotation', 'shadowY', 'dpr'])

const shared = []
const seen = new Set()
for (const path of [
  'content/docs/api/index.mdx',
  'content/docs/screen-content.mdx',
  'content/docs/api/mockup-canvas.mdx',
]) {
  for (const row of propTable(read(join(root, path)))) {
    if (seen.has(row.name) || CANVAS_ONLY_MACHINERY.has(row.name)) continue
    seen.add(row.name)
    shared.push(row)
  }
}

const byComponent = {}
for (const device of DEVICES) {
  const family = FAMILY_OF[device.component]
  if (!family || byComponent[device.component]) continue
  byComponent[device.component] = propTable(read(join(root, `content/family-reference/${family}.mdx`)))
}
for (const object of OBJECTS) {
  byComponent[object.component] = propTable(read(join(root, `content/docs/api/${object.id}.mdx`)))
}

/** A row per line, or nothing at all - an empty join would leave a hole. */
const serialise = (rows) =>
  rows.length ? `\n${rows.map((r) => `    ${JSON.stringify(r)}`).join(',\n')},\n  ` : ''

const output = `/* eslint-disable */
// AUTO-GENERATED by scripts/extract-prop-tables.mjs - do not edit by hand.
// Every prop each mockup accepts, lifted from the prop tables in the API docs
// so the explorer's inspector can show the whole surface, not just the parts
// it has a control for.

export interface PropDoc {
  name: string
  type: string
  default: string
  description: string
}

/** Props every mockup accepts, whatever it renders. */
export const SHARED_PROPS: PropDoc[] = [${serialise(shared)}]

/** Object-specific props, by component name. */
export const COMPONENT_PROPS: Record<string, PropDoc[]> = {
${Object.entries(byComponent)
  .map(([name, rows]) => `  ${JSON.stringify(name)}: [${serialise(rows)}]`)
  .join(',\n')},
}
`

writeFileSync(join(root, 'lib/prop-tables.generated.ts'), output)
console.log(
  `extracted ${shared.length} shared props and ${Object.keys(byComponent).length} component tables`
)
